let language = 'en';

export function resolveLanguage(saved, languages = globalThis.navigator?.languages ?? []) {
    if (saved === 'en' || saved === 'ko') return saved;
    for (const locale of languages) {
        const candidate = String(locale).toLowerCase().split('-')[0];
        if (candidate === 'en' || candidate === 'ko') return candidate;
    }
    return 'en';
}

export function getLanguage() { return language; }

export function setLanguage(value) {
    language = value === 'ko' ? 'ko' : 'en';
    return language;
}

export function t(source, params = {}, language = getLanguage()) {
    const message = language === 'ko' && Object.hasOwn(translations.ko, source) ? translations.ko[source] : source;
    return message.replace(/\{(\w+)\}/g, (placeholder, key) => Object.hasOwn(params, key) ? String(params[key]) : placeholder);
}
